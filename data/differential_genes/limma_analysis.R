
library(limma)
data <- read.csv("D:/code/Prediction-model-of-distant-metastasis-of-breast-cancer-main/data/preprocessed/preprocessed_data.csv", row.names=1, check.names=FALSE)
expr_cols <- setdiff(colnames(data), c("metastasis", "dataset"))
expr_data <- as.matrix(data[, expr_cols])
group <- factor(data$metastasis, levels=c(0, 1), labels=c("non_metastasis", "metastasis"))
design <- model.matrix(~0 + group)
colnames(design) <- levels(group)
fit <- lmFit(expr_data, design)
contrast.matrix <- makeContrasts(metastasis - non_metastasis, levels=design)
fit2 <- contrasts.fit(fit, contrast.matrix)
fit2 <- eBayes(fit2)
results <- topTable(fit2, number=Inf, adjust.method="BH", p.value=0.05, lfc=0.5)
write.csv(results, "D:/code/Prediction-model-of-distant-metastasis-of-breast-cancer-main/data/differential_genes/limma_results.csv", row.names=TRUE)
